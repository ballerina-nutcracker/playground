import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import { basename, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseDocument } from 'yaml';

const root = fileURLToPath(new URL('../', import.meta.url));
export const defaultOutput = resolve(root, 'packages/browser-workspace/src/generated/skills.ts');

export function parseSkill(filename, markdown) {
  const fail = message => { throw new Error(`${filename}: ${message}`); };
  const match = /^(?:\uFEFF)?---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/.exec(markdown);
  if (!match) fail('Expected YAML frontmatter followed by a Markdown instruction body.');
  const document = parseDocument(match[1], { uniqueKeys: true });
  if (document.errors.length) fail(`Invalid YAML frontmatter: ${document.errors[0].message}`);
  let metadata;
  try { metadata = document.toJS({ maxAliasCount: 0 }); }
  catch { fail('Frontmatter must not use YAML aliases.'); }
  if (!metadata || typeof metadata !== 'object' || Array.isArray(metadata)) fail('Frontmatter must be a mapping.');
  const { name, description } = metadata;
  if (typeof name !== 'string' || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) fail('name must be a lowercase, hyphen-separated identifier.');
  if (name !== basename(filename, '.md')) fail('name must match the Markdown filename stem.');
  if (typeof description !== 'string' || !description.trim()) fail('description must be a nonempty string.');
  if (!match[2].trim()) fail('Skill instructions must not be empty.');
  return { name, description: description.trim(), instructions: match[2] };
}

export async function generateSkills(sourceDirectory = resolve(root, 'skills'), outputFile = defaultOutput) {
  const files = (await readdir(sourceDirectory, { withFileTypes: true }))
    .filter(entry => entry.isFile() && entry.name.endsWith('.md')).map(entry => entry.name).sort();
  const skills = [];
  const names = new Set();
  for (const filename of files) {
    const skill = parseSkill(filename, await readFile(resolve(sourceDirectory, filename), 'utf8'));
    if (names.has(skill.name)) throw new Error(`${filename}: Duplicate skill name: ${skill.name}`);
    names.add(skill.name);
    skills.push(skill);
  }
  const content = `// Generated by scripts/build_skills.mjs. Do not edit.\nexport const bundledSkills = ${JSON.stringify(skills, null, 2)} as const;\n`;
  await mkdir(dirname(outputFile), { recursive: true });
  // Avoid needless dev-server reloads when no skill changed.
  if (await readFile(outputFile, 'utf8').catch(error => { if (error.code === 'ENOENT') return undefined; throw error; }) !== content) await writeFile(outputFile, content);
  return skills;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await generateSkills();
}
